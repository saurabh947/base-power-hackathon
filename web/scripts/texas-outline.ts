// Builds src/map/texasOutline.ts, the Texas outline drawn by the live map.
//
// Source: U.S. Census Bureau, 2023 Cartographic Boundary File, States,
// 1:5,000,000, KML (cb_2023_us_state_5m.kml),
// https://www2.census.gov/geo/tiger/GENZ2023/kml/cb_2023_us_state_5m.zip
// Licence: public domain, a work of the U.S. Government (17 U.S.C. § 105); the
// file's metadata lists no access constraints.
//
// Steps: take the Texas placemark's largest ring, project it with EPSG:3083
// (src/map/albers.ts, the same function the battery dots use), simplify it with
// Douglas–Peucker (src/map/geometry.ts), check it is still a simple polygon,
// round to 10 m and write the module.
//
// From web/ (or `make web-texas` from the repo root, which downloads the file first):
//   curl -sSLO https://www2.census.gov/geo/tiger/GENZ2023/kml/cb_2023_us_state_5m.zip
//   unzip -o cb_2023_us_state_5m.zip cb_2023_us_state_5m.kml
//   node scripts/texas-outline.ts cb_2023_us_state_5m.kml [tolerance in metres, default 2000]

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { projectLonLat } from '../src/map/albers.ts';
import { ringArea, ringBBox, ringSelfIntersects, simplifyRing } from '../src/map/geometry.ts';

const SOURCE_URL = 'https://www2.census.gov/geo/tiger/GENZ2023/kml/cb_2023_us_state_5m.zip';
const OUT = fileURLToPath(new URL('../src/map/texasOutline.ts', import.meta.url));
const DEFAULT_TOLERANCE_M = 2000;

function texasRings(kml: string): number[][] {
  const tag = '<SimpleData name="NAME">Texas</SimpleData>';
  const at = kml.indexOf(tag);
  if (at < 0) throw new Error('No Texas placemark in this file.');
  const start = kml.lastIndexOf('<Placemark', at);
  const end = kml.indexOf('</Placemark>', at);
  const placemark = kml.slice(start, end);
  const rings: number[][] = [];
  for (const m of placemark.matchAll(/<outerBoundaryIs>[\s\S]*?<coordinates>([\s\S]*?)<\/coordinates>/g)) {
    const lonlat: number[] = [];
    for (const tuple of m[1].trim().split(/\s+/)) {
      const [lon, lat] = tuple.split(',').map(Number);
      if (Number.isFinite(lon) && Number.isFinite(lat)) lonlat.push(lon, lat);
    }
    const n = lonlat.length;
    if (n >= 4 && lonlat[0] === lonlat[n - 2] && lonlat[1] === lonlat[n - 1]) lonlat.length = n - 2; // drop the closing point
    rings.push(lonlat);
  }
  if (!rings.length) throw new Error('The Texas placemark has no polygon.');
  return rings;
}

function project(lonlat: number[]): number[] {
  const out: number[] = [];
  for (let i = 0; i < lonlat.length; i += 2) out.push(...projectLonLat(lonlat[i], lonlat[i + 1]));
  return out;
}

function main(): void {
  const [file, tol] = process.argv.slice(2);
  if (!file) {
    console.error('usage: node scripts/texas-outline.ts cb_2023_us_state_5m.kml [tolerance_m]');
    process.exit(2);
  }
  const tolerance = tol ? Number(tol) : DEFAULT_TOLERANCE_M;
  const rings = texasRings(readFileSync(file, 'utf8')).map((lonlat) => ({ lonlat, xy: project(lonlat) }));
  rings.sort((a, b) => Math.abs(ringArea(b.xy)) - Math.abs(ringArea(a.xy)));
  const largest = rings[0];
  const simplified = simplifyRing(largest.xy, tolerance).map((v) => Math.round(v / 10) * 10);
  if (ringSelfIntersects(simplified)) throw new Error(`Simplifying at ${tolerance} m made the outline cross itself.`);
  const points = simplified.length / 2;
  const bbox = ringBBox(simplified);
  const areaKm2 = Math.abs(ringArea(simplified)) / 1e6;
  const sourceAreaKm2 = Math.abs(ringArea(largest.xy)) / 1e6;

  const rows: string[] = [];
  for (let i = 0; i < simplified.length; i += 8) rows.push(`  ${simplified.slice(i, i + 8).join(', ')},`);
  const text = `// GENERATED by web/scripts/texas-outline.ts. Do not edit by hand; re-run the script instead.
//
// Source: U.S. Census Bureau, 2023 Cartographic Boundary File, States, 1:5,000,000
// (cb_2023_us_state_5m.kml), ${SOURCE_URL}
// Licence: public domain, a work of the U.S. Government (17 U.S.C. § 105); no access constraints.
// The largest Texas ring (${largest.lonlat.length / 2} of ${rings.reduce((a, r) => a + r.lonlat.length / 2, 0)} points in ${rings.length} ring${rings.length === 1 ? '' : 's'}),
// projected to EPSG:3083 (src/map/albers.ts) and simplified with Douglas–Peucker at ${tolerance} m
// to ${points} points, rounded to 10 m. Area ${Math.round(areaKm2).toLocaleString('en-US')} km² (source ring ${Math.round(sourceAreaKm2).toLocaleString('en-US')} km²).

export const TEXAS_OUTLINE_SOURCE = {
  title: 'U.S. Census Bureau, 2023 Cartographic Boundary File, States, 1:5,000,000',
  url: '${SOURCE_URL}',
  licence: 'Public domain (U.S. Government work)',
  projection: 'EPSG:3083',
  toleranceM: ${tolerance},
  points: ${points},
} as const;

/** EPSG:3083 metres of the outline's bounding box. */
export const TEXAS_BBOX = { minX: ${bbox.minX}, minY: ${bbox.minY}, maxX: ${bbox.maxX}, maxY: ${bbox.maxY} } as const;

/** The outline as [x0, y0, x1, y1, …] in EPSG:3083 metres (y north), closing point left out. */
export const TEXAS_OUTLINE: readonly number[] = [
${rows.join('\n')}
];
`;
  writeFileSync(OUT, text);
  console.info(`${points} points (from ${largest.lonlat.length / 2}) at ${tolerance} m; area ${Math.round(areaKm2)} km² vs ${Math.round(sourceAreaKm2)} km²; wrote ${OUT}`);
}

main();
